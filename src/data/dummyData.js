const now = new Date("2026-09-02T10:00:00+05:30");
const daysAgo = (n, h = 10, m = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() - n);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};
const daysAhead = (n, h = 10, m = 0) => {
  const d = new Date(now);
  d.setDate(d.getDate() + n);
  d.setHours(h, m, 0, 0);
  return d.toISOString();
};

